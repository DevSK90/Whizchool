import { createHmac, randomUUID, timingSafeEqual } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve, sep } from "node:path";
import type { FileRef } from "@whizchool/shared/types";
import { config } from "./config";

/**
 * Where file bytes live. Local disk now; an S3-compatible store (Cloudflare R2) plugs in behind
 * the same three calls at deployment.
 */
interface ObjectStore {
  put(key: string, data: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  remove(key: string): Promise<void>;
}

const root = resolve(config.STORAGE_DIR);

function pathFor(key: string) {
  const p = resolve(root, key);
  // Keys are generated by us, but never let one escape the storage folder.
  if (!p.startsWith(root + sep)) throw new Error(`Invalid storage key: ${key}`);
  return p;
}

const localDisk: ObjectStore = {
  async put(key, data) {
    const p = pathFor(key);
    await mkdir(dirname(p), { recursive: true });
    await writeFile(p, data);
  },
  get: (key) => readFile(pathFor(key)),
  remove: (key) => rm(pathFor(key), { force: true }),
};

export const store = localDisk;

const EXTENSIONS: Record<string, string> = { "application/pdf": "pdf", "image/jpeg": "jpg", "image/png": "png", "image/webp": "webp" };

/** "2026/10/<uuid>.pdf": unguessable, and spread over folders by month. */
export function newStorageKey(mimeType: string) {
  const now = new Date();
  return `${now.getUTCFullYear()}/${String(now.getUTCMonth() + 1).padStart(2, "0")}/${randomUUID()}.${EXTENSIONS[mimeType] ?? "bin"}`;
}

// ── Signed links ──
// Files are private. The API hands out links that work for an hour, so images and PDFs can be
// opened directly by the browser without exposing a permanent address.

const LINK_TTL_S = 60 * 60;

const signature = (fileId: string, expires: number) =>
  createHmac("sha256", config.FILE_URL_SECRET).update(`${fileId}.${expires}`).digest("base64url");

export function signedFileUrl(fileId: string, now = Date.now()) {
  // Rounded to 10 minutes so repeated reads give the same URL and the browser cache can reuse it.
  const expires = Math.ceil(now / 1000 / 600) * 600 + LINK_TTL_S;
  return `/api/v1/files/${fileId}?expires=${expires}&signature=${signature(fileId, expires)}`;
}

export function verifyFileSignature(fileId: string, expires: number, given: string) {
  if (!Number.isInteger(expires) || expires * 1000 < Date.now()) return false;
  const expected = Buffer.from(signature(fileId, expires));
  const actual = Buffer.from(given);
  return expected.length === actual.length && timingSafeEqual(expected, actual);
}

export function toFileRef(f: { id: string; name: string; size: number; mimeType: string }): FileRef {
  return { id: f.id, name: f.name, size: f.size, mimeType: f.mimeType, url: signedFileUrl(f.id) };
}
